/// LLVM IR opcode categories for pattern matching.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum LlvmOp {
    Add,
    FAdd,
    Sub,
    FSub,
    Mul,
    FMul,
    SDiv,
    UDiv,
    FDiv,
    And,
    Or,
    Xor,
    Shl,
    LShr,
    AShr,
    ICmp,
    FCmp,
    Load,
    Store,
    Br,
    Ret,
    Call,
    Alloca,
    GetElementPtr,
    BitCast,
    Trunc,
    ZExt,
    SExt,
    FPToUI,
    FPToSI,
    UIToFP,
    SIToFP,
    FPTrunc,
    FPExt,
    Select,
    Phi,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IrType {
    I1,
    I8,
    I16,
    I32,
    I64,
    F16,
    F32,
    F64,
    Ptr,
}
